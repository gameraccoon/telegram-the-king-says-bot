package staticFunctions

import (
	"testing"

	"github.com/stretchr/testify/require"
)

func TestCanSafelyConsume(t *testing.T) {
	assert := require.New(t)

	// exact role matches always consumed
	assert.True(canSafelyConsume(0, 0, &[4]int{8, 8, 8, 8}, &[3]int{1, 0, 0}))
	assert.True(canSafelyConsume(1, 1, &[4]int{8, 8, 8, 8}, &[3]int{0, 1, 0}))
	assert.True(canSafelyConsume(2, 2, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 1}))
	// required roles outside first three are never consumed
	assert.False(canSafelyConsume(0, NumericPositionMatchTypeOffset, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	assert.False(canSafelyConsume(1, NumericPositionMatchTypeOffset, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	assert.False(canSafelyConsume(2, NumericPositionMatchTypeOffset, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	assert.False(canSafelyConsume(0, 3 /*incorrect*/, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	assert.False(canSafelyConsume(1, 3 /*incorrect*/, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	assert.False(canSafelyConsume(2, 3 /*incorrect*/, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 0}))
	// incompatible roles are never consumed
	assert.False(canSafelyConsume(0, 1, &[4]int{8, 8, 8, 8}, &[3]int{0, 1, 0}))
	assert.False(canSafelyConsume(0, 2, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 1}))
	assert.False(canSafelyConsume(1, 2, &[4]int{8, 8, 8, 8}, &[3]int{0, 0, 1}))
	assert.False(canSafelyConsume(2, 1, &[4]int{8, 8, 8, 8}, &[3]int{0, 1, 0}))
	// user roles 1 and 2 are only consumed by "any" required role if there is enough players
	// to later consume for the specific required role of the player we want to consume (exception below)
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 0, 0}, &[3]int{1, 1, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{2, 2, 0, 0}, &[3]int{1, 2, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{2, 1, 0, 1}, &[3]int{1, 2, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{1, 1, 0, 2}, &[3]int{1, 2, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 1, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 1, 0}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 0, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 2, 0, 0}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 1}, &[3]int{1, 1, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 1, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 0, 0}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 0, 1, 0}, &[3]int{1, 0, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{2, 0, 2, 0}, &[3]int{1, 0, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{2, 0, 1, 1}, &[3]int{1, 0, 2}))
	assert.True(canSafelyConsume(2, 0, &[4]int{1, 0, 1, 2}, &[3]int{1, 0, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 0, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 1, 1, 0}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 0, 0}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 2, 0}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 1}, &[3]int{1, 0, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 1, 1, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 0, 0}))
	// The exception to the rule above is the case when there are missing players going to be left
	// and consuming this players won't increase the amount of missing players
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 2, 0}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 0}, &[3]int{1, 2, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 1, 0}, &[3]int{2, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 2, 0, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{0, 1, 0, 1}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(1, 0, &[4]int{1, 2, 0, 0}, &[3]int{2, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 0, 2}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 0}, &[3]int{1, 1, 2}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 1, 1, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 1, 1, 0}, &[3]int{2, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 2, 0}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{0, 0, 1, 1}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(2, 0, &[4]int{1, 0, 2, 1}, &[3]int{2, 1, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 0, 0}, &[3]int{1, 2, 0}))
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 0, 0}, &[3]int{1, 1, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{1, 1, 0, 0}, &[3]int{1, 2, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{2, 1, 0, 0}, &[3]int{1, 2, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{3, 1, 0, 0}, &[3]int{1, 2, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{2, 2, 0, 0}, &[3]int{1, 2, 1}))
	assert.False(canSafelyConsume(1, 0, &[4]int{2, 1, 0, 0}, &[3]int{1, 1, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 0, 1, 0}, &[3]int{1, 0, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 0, 1, 0}, &[3]int{1, 1, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{1, 0, 1, 0}, &[3]int{1, 1, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{2, 0, 1, 0}, &[3]int{1, 1, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{2, 0, 2, 0}, &[3]int{1, 1, 2}))
	assert.False(canSafelyConsume(2, 0, &[4]int{2, 0, 1, 0}, &[3]int{1, 1, 1}))
	assert.False(canSafelyConsume(2, 0, &[4]int{3, 0, 1, 0}, &[3]int{1, 1, 2}))
	// users role "both" are only consumed by role 0 if both other required roles can be
	// fulfilled without these users (an exception below)
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 1}, &[3]int{1, 0, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 1}, &[3]int{1, 1, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 1}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 2}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 0, 1, 1}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 1, 1}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 2}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 1, 1}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 2}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 1, 0, 1}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 2}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 1, 0, 1}, &[3]int{1, 1, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 0, 0, 2}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 1, 1, 2}, &[3]int{1, 2, 0}))
	assert.True(canSafelyConsume(3, 0, &[4]int{1, 1, 1, 2}, &[3]int{1, 2, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 1, 1, 1}, &[3]int{1, 2, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{0, 1, 1, 2}, &[3]int{1, 3, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 1, 1, 2}, &[3]int{1, 3, 0}))
	// The exception to the rule above is the case when there are missing players going to be left
	// and consuming this players won't increase the amount of missing players
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 1}, &[3]int{1, 1, 0}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 1}, &[3]int{1, 0, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 1}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 0, 0, 2}, &[3]int{1, 1, 1}))
	assert.True(canSafelyConsume(3, 0, &[4]int{0, 1, 1, 2}, &[3]int{1, 4, 0}))
	assert.False(canSafelyConsume(3, 0, &[4]int{2, 0, 0, 1}, &[3]int{1, 1, 1}))
	assert.False(canSafelyConsume(3, 0, &[4]int{1, 1, 1, 2}, &[3]int{1, 4, 0}))
	// users with role "both" are only consumed by roles, if the opposite role has enough
	// players to be fulfilled. (an exception below)
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 0, 0, 1}, &[3]int{0, 1, 0}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 0, 1, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 0, 0, 2}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 1, 1, 1}, &[3]int{0, 1, 1}))
	assert.False(canSafelyConsume(3, 1, &[4]int{0, 1, 0, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 2, 1, 4}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 2, 1, 3}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 3, 1, 3}, &[3]int{0, 3, 3}))
	assert.False(canSafelyConsume(3, 1, &[4]int{0, 3, 1, 2}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 0, 0, 1}, &[3]int{0, 0, 1}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 0, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 0, 0, 2}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 1, 1}, &[3]int{0, 1, 1}))
	assert.False(canSafelyConsume(3, 2, &[4]int{0, 0, 1, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 2, 4}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 2, 3}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 3, 3}, &[3]int{0, 3, 3}))
	assert.False(canSafelyConsume(3, 2, &[4]int{0, 1, 3, 2}, &[3]int{0, 3, 3}))
	// The exception to the rule above is that if the current role may be missing players
	// without this player (or even with this player)
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 0, 0, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 0, 0, 1}, &[3]int{0, 1, 1}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 1, 0, 2}, &[3]int{0, 2, 2}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 0, 2}, &[3]int{0, 2, 2}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 2, 1, 2}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 2, 1, 2}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 1, &[4]int{0, 1, 2, 2}, &[3]int{0, 3, 3}))
	assert.True(canSafelyConsume(3, 2, &[4]int{0, 1, 2, 2}, &[3]int{0, 3, 3}))
	assert.False(canSafelyConsume(3, 1, &[4]int{0, 3, 1, 1}, &[3]int{0, 3, 3}))
	assert.False(canSafelyConsume(3, 2, &[4]int{0, 1, 3, 1}, &[3]int{0, 3, 3}))
}
